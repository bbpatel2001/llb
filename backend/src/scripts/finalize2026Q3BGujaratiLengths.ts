(async () => {
  await connectDB();
  try {
    for (const [targetMarks, addition, marker] of [[5, add5, 'કેબિનેટ મિશન યોજના બંધારણ રચનાની'], [15, add15, 'કેબિનેટ મિશન યોજનાની બીજી વિશેષતા']] as const) {
      const answer: any = await Answer.findOne({ questionId, targetMarks, language: 'gu' });
      if (!answer) throw new Error(`Missing Gujarati ${targetMarks}-mark answer`);
      if (!String(answer.text).includes(marker)) answer.text += addition;
      answer.wordCount = String(answer.text).split(/\s+/).filter(Boolean).length;
      answer.reviewStatus = 'review_required'; answer.verified = false;
      await answer.save();
      console.log(JSON.stringify({ targetMarks, language: 'gu', wordCount: answer.wordCount }));
    }
  } finally { await disconnectDB(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
