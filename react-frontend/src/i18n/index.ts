export type TranslationKey = keyof typeof translations.en;

export function isLocale(value: string | null): value is Locale {
  return value === 'en' || value === 'gu';
}

export function translate(locale: Locale, key: TranslationKey, variables: Record<string, string | number> = {}): string {
  const template = translations[locale][key] || translations.en[key];
  return template.replace(/\{(\w+)\}/g, (_match, variable: string) => String(variables[variable] ?? `{${variable}}`));
}
